#!/usr/bin/env bash
# Останавливает фоновый трекер и отпускает камеру.
# Шаблон нарочно узкий: только браузер с профилем трекера. Широкий pkill -f
# ловил бы любую команду, где просто упомянуто имя службы, включая свою же.
if pkill -f '/app/extra/chrome.*yeahtrack[-]daemon'; then
  echo "фоновый трекер остановлен"
else
  echo "не запущен"
fi
